#!/usr/bin/env python3
"""Generate firmware/main/demo_fall.h: a short synthetic fall the device can play into its
own motion-sensor stream on request (double press of the button, or "Simulate a fall" in
the web app). That shows the whole alert chain on real hardware without anyone falling:
the real model detects the clip and the pre-alarm starts; then, exactly as after a real
fall, pressing "I'm OK" within 10 s cancels it, otherwise ALERT_FALL is sent (after 5 s
of stillness, or when the 10 s run out).

The clip is 2.5 s of activity, a synthetic fall (the same generator as the replay
scenario, no KFall data) and 3 s lying still. It is checked here with the Python model of
the device in three situations before the header is written.

    python firmware/tools/gen_demo_fall.py --repo .
"""
import argparse
import os
import sys

import numpy as np


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", default=".")
    a = ap.parse_args()
    repo = os.path.abspath(a.repo)
    here = os.path.dirname(os.path.abspath(__file__))
    sys.path[:0] = [repo, os.path.join(repo, "firmware", "test", "host"), here]
    import device_model as DM
    import phase1_pipeline as P
    from gen_replay import ACC_LSB, FS, GYR_LSB, load_synthetic, lying_after, still
    from gen_vectors import load_header

    hp = load_header(os.path.join(repo, "fall_model_data.h"))
    q8 = P.Int8Model(open(os.path.join(repo, "fall_model_int8.tflite"), "rb").read())
    recs = load_synthetic(P)
    rng = np.random.default_rng(7)
    lsb = np.array([ACC_LSB] * 3 + [GYR_LSB] * 3)

    x = recs["F01_SA01_R01"]
    imp = int(np.argmax(np.linalg.norm(x[:, :3], axis=1)))
    clip = lying_after(x[max(0, imp - int(2.5 * FS)):imp + int(0.5 * FS)], 3.0, rng)
    counts = np.clip(np.round(clip * lsb), -32768, 32767).astype(np.int16)

    stand = np.array([0.0, -1.0, 0.05, 0, 0, 0])
    flat = np.array([0.0, 0.05, 1.0, 0, 0, 0])

    def run(before, after, press_after_clip_s=None):
        """Live data, then the clip exactly as the firmware substitutes it, then live data."""
        c = np.vstack([np.clip(np.round(before * lsb), -32768, 32767).astype(np.int16), counts,
                       np.clip(np.round(after * lsb), -32768, 32767).astype(np.int16)])
        ph = (c / lsb).astype(np.float32)
        zeros = np.zeros(2 * len(ph))            # no finger on the pulse sensor
        acts = [] if press_after_clip_s is None else [(len(before) + len(counts) + int(press_after_clip_s * FS), 1)]
        dev = DM.simulate(P, hp, q8, c, ph, zeros, zeros, acts)
        t0 = len(before) / FS
        return [(round(t - t0, 2), DM.EV_NAMES[e]) for t, e in dev.events]

    cases = [
        ("upright and still, then the device is laid flat", run(still(stand, 10, rng), still(flat, 25, rng)),
         ["FALL_SUSPECTED", "ALERT_FALL"]),
        ("walking, then the device is laid flat", run(recs["D01_SA01_R01"][:10 * FS], still(flat, 25, rng)),
         ["FALL_SUSPECTED", "ALERT_FALL"]),
        ("upright, then the worker presses I'm OK", run(
            still(stand, 10, rng), recs["D01_SA01_R02"][:25 * FS], press_after_clip_s=1.0),
         ["FALL_SUSPECTED", "CANCELLED"]),
    ]
    ok = True
    for name, events, need in cases:
        names = [e for _, e in events]
        good = all(any(n.startswith(k) for n in names) for k in need) and (
            "ALERT_FALL" in need or not any(n.startswith("ALERT_FALL") for n in names))
        ok &= good
        print(f"{'ok ' if good else 'BAD'} {name}: {events or 'no events'} (clip starts at 0 s, "
              f"impact at {2.5:.1f} s, clip ends at {len(clip) / FS:.1f} s)")
    if not ok:
        sys.exit("the demo clip does not behave as intended; not writing the header")

    rows = [", ".join(str(int(v)) for v in row) for row in counts]
    L = ["// Auto-generated by firmware/tools/gen_demo_fall.py -- DO NOT EDIT BY HAND",
         "// Synthetic fall (no KFall data) played into the IMU stream for demonstrations:",
         "// 2.5 s of activity, the impact, 3 s lying still. MPU6050 counts in the KFall frame",
         "// (+-16 g: 2048 LSB/g, +-2000 dps: 16.4 LSB/dps), 50 Hz.",
         "#pragma once", "#include <stdint.h>", "",
         f"#define DEMO_FALL_N {len(counts)}", "",
         f"static const int16_t DEMO_FALL[DEMO_FALL_N][6] = {{"]
    L += [f"  {{{r}}}," for r in rows] + ["};", ""]
    out = os.path.join(repo, "firmware", "main", "demo_fall.h")
    open(out, "w").write("\n".join(L))
    print(f"wrote {out} ({len(counts)} samples, {len(counts) / FS:.1f} s)")


if __name__ == "__main__":
    main()
