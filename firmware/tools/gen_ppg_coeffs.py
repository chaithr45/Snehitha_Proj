#!/usr/bin/env python3
"""Generate sc_ppg_coeffs.h: the PPG band-pass filter used by estimate_hr/estimate_spo2
in phase1_pipeline.py (2nd-order Butterworth band-pass 0.5-4 Hz at 100 Hz, SOS form).

Usage: python firmware/tools/gen_ppg_coeffs.py > firmware/components/safety_core/include/sc_ppg_coeffs.h
"""
from scipy.signal import butter

FS = 100
sos = butter(2, [0.5, 4.0], btype="band", fs=FS, output="sos")
print("// Auto-generated by firmware/tools/gen_ppg_coeffs.py -- DO NOT EDIT BY HAND")
print("// PPG band-pass: Butterworth order 2, 0.5-4.0 Hz, fs = 100 Hz (matches phase1_pipeline.py)")
print("#pragma once")
print(f"#define SC_PPG_COEFFS_FS   {FS}   // must equal SC_PPG_FS in safety_core.h")
print(f"#define SC_PPG_SECTIONS    {len(sos)}")
print("// SOS rows: b0 b1 b2 a0 a1 a2 (double precision, same values SciPy uses)")
print(f"static const double SC_PPG_SOS[{len(sos)}][6] = {{")
for r in sos:
    print("  {" + ", ".join(f"{v:.17g}" for v in r) + "},")
print("};")
